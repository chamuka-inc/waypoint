  await page.locator('.nav-item[data-nav="discover"]').click();
  await page.locator('.role-open').click();
  check(await page.locator('.source-link').count() === 1, 'Sourced research has a real link field and freshness context');
  await page.keyboard.press('Escape');
  await page.locator('.role-selector input').check();
  page.once('dialog', dialog => dialog.accept());
  await page.locator('[data-action="remove-selected"]').click();
  await page.waitForFunction(() => document.querySelectorAll('.role-card').length === 0);
  check(service.state.roles.length === 0, 'Selected opportunities can be removed with related workspace data');
  await page.locator('.nav-item[data-nav="profile"]').click();
  const unsavedAmbition = 'Unsaved direction that should require explicit confirmation.';
  await page.locator('[name="ambitions"]').fill(unsavedAmbition);
