  await page.locator('[name="name"]').fill('Jamie Rivers');
  await page.locator('[name="location"]').fill('Manchester, UK');
  await page.locator('#cv-upload').setInputFiles({ name: 'cv.txt', mimeType: 'text/plain', buffer: Buffer.from('Product manager with six years of experience leading cross-functional teams, customer research and measurable improvements to onboarding. Led a team of eight and improved customer activation by 24 percent.') });
